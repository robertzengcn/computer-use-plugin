import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readFile, rm, writeFile, cp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  checkDeclarationDrift,
  generateDeclarations,
  writeDeclarations,
} from '../../tooling/contracts/generate-types.js';
import { buildContractArchive } from '../../tooling/contracts/archive.js';

const REPO = process.cwd();
const CONTRACTS = join(REPO, 'contracts');

describe('declaration generation', () => {
  it('is deterministic across runs', async () => {
    const first = await generateDeclarations(CONTRACTS);
    const second = await generateDeclarations(CONTRACTS);
    expect([...first.keys()].sort()).toEqual([...second.keys()].sort());
    for (const [name, content] of first) {
      expect(second.get(name)).toBe(content);
    }
  });

  it('covers every registered schema', async () => {
    const generated = await generateDeclarations(CONTRACTS);
    expect(generated.size).toBeGreaterThanOrEqual(12);
    expect([...generated.keys()]).toContain('desktop/error-v1');
    expect([...generated.keys()]).toContain('models/model-manifest-v1');
  });

  it('committed declarations have no drift', async () => {
    const drift = await checkDeclarationDrift(CONTRACTS);
    expect(drift).toEqual([]);
  });

  it('detects drift when a committed declaration is tampered with', async () => {
    const tempContracts = await mkdtemp(join(tmpdir(), 'cu-types-'));
    await cp(CONTRACTS, tempContracts, { recursive: true });
    const typesDir = join(tempContracts, 'types');
    await mkdir(typesDir, { recursive: true });
    const generated = await generateDeclarations(tempContracts);
    for (const [name, content] of generated) {
      await writeFile(join(typesDir, `${name}.d.ts`), content);
    }
    await writeFile(join(typesDir, 'desktop', 'error-v1.d.ts'), 'export interface Tampered {}\n');
    const drift = await checkDeclarationDrift(tempContracts);
    expect(drift).toContain('desktop/error-v1');
    await rm(tempContracts, { recursive: true, force: true });
  });

  it('writeDeclarations produces the exact generated bytes on disk', async () => {
    const tempContracts = await mkdtemp(join(tmpdir(), 'cu-write-'));
    await cp(CONTRACTS, tempContracts, { recursive: true });
    const written = await writeDeclarations(tempContracts);
    expect(written.length).toBeGreaterThanOrEqual(12);
    const onDisk = await readFile(join(tempContracts, 'types', 'desktop', 'error-v1.d.ts'), 'utf8');
    const generated = await generateDeclarations(tempContracts);
    expect(onDisk).toBe(generated.get('desktop/error-v1'));
    await rm(tempContracts, { recursive: true, force: true });
  });
});

describe('contract archive (contracts:build)', () => {
  it('produces a checksummed closure and zip with identical contents', async () => {
    const outDir = await mkdtemp(join(tmpdir(), 'cu-archive-'));
    const result = await buildContractArchive(REPO, outDir);
    expect(result.version).toBe('v1');
    expect(result.fileCount).toBeGreaterThanOrEqual(40);

    const manifest = JSON.parse(await readFile(join(result.archiveDir, 'manifest.json'), 'utf8')) as {
      version: string;
      digest: string;
      files: { path: string; sha256: string }[];
    };
    expect(manifest.files.length).toBe(result.fileCount);
    // Every listed file exists and matches its recorded hash.
    for (const file of manifest.files.slice(0, 5)) {
      const bytes = await readFile(join(result.archiveDir, file.path));
      expect(createHash('sha256').update(bytes).digest('hex')).toBe(file.sha256);
    }
    // The zip exists and its recorded digest matches its bytes.
    const zipBytes = await readFile(result.zipPath);
    expect(result.zipSha256).toBe(createHash('sha256').update(zipBytes).digest('hex'));
    await rm(outDir, { recursive: true, force: true });
  });
});
